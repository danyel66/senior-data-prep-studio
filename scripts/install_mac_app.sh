#!/bin/bash
# Creates "Senior Data Prep Studio.app" in ~/Applications, so the studio opens from the Dock,
# Launchpad or Spotlight like any other app, with no terminal.
#
# The app is a small launcher: it runs this project with your existing Python environment, so
# updates (git pull) take effect immediately and nothing needs rebuilding.
#
# Usage (from anywhere):   bash scripts/install_mac_app.sh
# Options (environment):   SDPS_PYTHON=/path/to/python   SDPS_APP_DIR=/other/folder
set -euo pipefail

APP_NAME="Senior Data Prep Studio"
BUNDLE_ID="com.sdps.seniordataprepstudio"
PROJECT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
if [ -n "${SDPS_PYTHON:-}" ]; then
    PY="$SDPS_PYTHON"
elif [ -n "${VIRTUAL_ENV:-}" ] && [ -x "$VIRTUAL_ENV/bin/python" ]; then
    PY="$VIRTUAL_ENV/bin/python"
else
    PY="$HOME/.venvs/sdps/bin/python"
fi
DEST_DIR="${SDPS_APP_DIR:-$HOME/Applications}"
APP="$DEST_DIR/$APP_NAME.app"

fail() { printf '\n\033[31m✗ %s\033[0m\n\n' "$1" >&2; exit 1; }
ok()   { printf '\033[32m✓\033[0m %s\n' "$1"; }
warn() { printf '\033[33m!\033[0m %s\n' "$1"; }

echo "Installing $APP_NAME"
echo "  project: $PROJECT"
echo "  python:  $PY"
echo

[ -f "$PROJECT/main.py" ] || fail "Can't find main.py in $PROJECT. Run this script from inside the project."
[ -x "$PY" ] || fail "No Python at $PY.
  Create the environment first:
    python3.12 -m venv ~/.venvs/sdps && source ~/.venvs/sdps/bin/activate
    pip install -r requirements.txt"

"$PY" - <<'PYCHECK' || fail "The Python environment isn't ready (see above). Activate it and run: pip install -r requirements.txt"
import sys
if sys.version_info < (3, 11):
    sys.exit(f"Python {sys.version.split()[0]} is too old; 3.11+ is required.")
missing = []
for module in ("PyQt6.QtWidgets", "duckdb", "pandas", "numpy", "psutil"):
    try:
        __import__(module)
    except Exception as exc:
        missing.append(f"{module} ({exc.__class__.__name__})")
if missing:
    sys.exit("Missing packages: " + ", ".join(missing))
PYCHECK
ok "Python environment has everything the app needs"

case "$PY" in
    "$HOME/Documents/"*|"$HOME/Desktop/"*|*"/Library/Mobile Documents/"*)
        warn "Your Python environment is inside an iCloud-synced folder; iCloud can delete its files."
        warn "Recommended: python3.12 -m venv ~/.venvs/sdps (outside Documents/Desktop)." ;;
esac

VERSION="$("$PY" -c "import sys; sys.path.insert(0, sys.argv[1]); import sdps; print(sdps.__version__)" "$PROJECT")"

mkdir -p "$DEST_DIR"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# ---- icon ----------------------------------------------------------------------------------
if command -v iconutil >/dev/null 2>&1; then
    iconutil -c icns "$PROJECT/assets/AppIcon.iconset" -o "$APP/Contents/Resources/AppIcon.icns"
    ok "App icon"
else
    warn "iconutil not found (not macOS?): the app will use a generic icon"
fi

# ---- Info.plist ----------------------------------------------------------------------------
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key><string>$APP_NAME</string>
    <key>CFBundleDisplayName</key><string>$APP_NAME</string>
    <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
    <key>CFBundleExecutable</key><string>launcher</string>
    <key>CFBundleIconFile</key><string>AppIcon</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>$VERSION</string>
    <key>CFBundleVersion</key><string>$VERSION</string>
    <key>LSMinimumSystemVersion</key><string>11.0</string>
    <key>LSApplicationCategoryType</key><string>public.app-category.developer-tools</string>
    <key>NSHighResolutionCapable</key><true/>
    <key>NSRequiresAquaSystemAppearance</key><false/>
</dict>
</plist>
PLIST
ok "Info.plist (version $VERSION)"

# ---- launcher --------------------------------------------------------------------------------
LAUNCHER="$APP/Contents/MacOS/launcher"
{
    printf '#!/bin/bash\n# Generated by scripts/install_mac_app.sh. Re-run that script if you move the project.\n'
    printf 'PROJECT=%q\nPY=%q\n' "$PROJECT" "$PY"
    cat <<'LAUNCH'
LOG_DIR="$HOME/Library/Logs/SeniorDataPrepStudio"
LOG="$LOG_DIR/app.log"
mkdir -p "$LOG_DIR"

alert() {
    /usr/bin/osascript -e "display alert \"Senior Data Prep Studio\" message \"$1\" as critical" >/dev/null 2>&1 || true
}

if [ ! -f "$PROJECT/main.py" ]; then
    alert "The project folder was not found: $PROJECT. If you moved it, run scripts/install_mac_app.sh again from its new location."
    exit 1
fi
if [ ! -x "$PY" ]; then
    alert "The Python environment was not found: $PY. Recreate it (python3.12 -m venv ~/.venvs/sdps, then pip install -r requirements.txt) and run scripts/install_mac_app.sh again."
    exit 1
fi
if ! "$PY" -c 'import sys; sys.exit(sys.version_info < (3, 11))' >/dev/null 2>&1; then
    alert "The Python at $PY is older than 3.11. Recreate the environment with Python 3.12."
    exit 1
fi

# keep the log small: rotate at 1 MB
if [ -f "$LOG" ] && [ "$(stat -f%z "$LOG" 2>/dev/null || stat -c%s "$LOG")" -gt 1048576 ]; then
    mv -f "$LOG" "$LOG.old"
fi
echo "=== $(date '+%Y-%m-%d %H:%M:%S') launch ===" >> "$LOG"

cd "$PROJECT"
export SDPS_LAUNCHED_FROM_APP=1
exec "$PY" main.py >> "$LOG" 2>&1
LAUNCH
} > "$LAUNCHER"
chmod +x "$LAUNCHER"
ok "Launcher"

# ---- register with LaunchServices so Spotlight / Launchpad find it right away -----------------
LSREGISTER="/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister"
[ -x "$LSREGISTER" ] && "$LSREGISTER" -f "$APP" >/dev/null 2>&1 || true
touch "$APP"

echo
ok "Installed: $APP"
echo
echo "  Open it:          Spotlight (Cmd+Space) → \"Senior Data Prep Studio\", or Launchpad"
echo "  Keep it handy:    while it's running, right-click its Dock icon → Options → Keep in Dock"
echo "  If it won't open: see ~/Library/Logs/SeniorDataPrepStudio/app.log"
echo "  After moving the project or recreating the environment, run this script again."
if command -v open >/dev/null 2>&1; then
    open -R "$APP" || true
fi
